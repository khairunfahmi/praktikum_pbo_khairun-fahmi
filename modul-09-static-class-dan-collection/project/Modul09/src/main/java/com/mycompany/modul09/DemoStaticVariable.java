package com.mycompany.modul09;

public class DemoStaticVariable {

    public static void main(String[] args) {
        BerbagiNilai a = new BerbagiNilai(4, 4);
        System.out.println(a);
        System.out.println();

        BerbagiNilai b = new BerbagiNilai(8, 2);
        System.out.println(a);
        System.out.println(b);
        System.out.println();

        BerbagiNilai c = new BerbagiNilai(6, 22);
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
    }
}